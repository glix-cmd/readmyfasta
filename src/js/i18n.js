function fmtN(n, digits) {
  const lang = (window.APP_LANG || 'es') === 'en' ? 'en-US' : 'es-ES';
  if (n === null || n === undefined || Number.isNaN(n)) return '—';
  return Number(n).toLocaleString(lang, digits !== undefined ? { maximumFractionDigits: digits, minimumFractionDigits: 0 } : undefined);
}
